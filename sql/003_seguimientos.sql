CREATE TABLE IF NOT EXISTS chatfuel_seguimientos (
  canal VARCHAR(16) CHARACTER SET ascii NOT NULL,
  telefono VARCHAR(20) CHARACTER SET ascii NOT NULL,
  datos JSON NOT NULL,
  creado_en DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  actualizado_en DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (canal,telefono)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chatfuel_seguimientos_reparto (
  id SMALLINT PRIMARY KEY,
  turno BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS chatfuel_seguimientos_cursor (
  id SMALLINT PRIMARY KEY,
  ultimo_id BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
